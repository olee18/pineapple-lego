/* Pineapple — offline app shell */
const CACHE = "brickbloom-v76";
const ASSETS = [
  "./",
  "./index.html",
  "./styles.css",
  "./game.js",
  "./i18n.js",
  "./favicon.svg",
  "./logo.svg",
  "./manifest.webmanifest",
  "./vendor/three.min.js",
  "./icons/icon-192.png",
  "./icons/icon-512.png",
];

self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE)
      .then((cache) => cache.addAll(ASSETS))
      .then(() => self.skipWaiting())
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches.keys()
      .then((keys) => Promise.all(keys.filter((key) => key !== CACHE).map((key) => caches.delete(key))))
      .then(() => self.clients.claim())
  );
});

self.addEventListener("fetch", (event) => {
  if (event.request.method !== "GET") return;
  const url = new URL(event.request.url);
  if (url.origin !== self.location.origin) return;

  if (event.request.mode === "navigate") {
    event.respondWith(
      fetch(event.request)
        .then((response) => {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put("./index.html", copy));
          return response;
        })
        .catch(() => caches.match("./index.html"))
    );
    return;
  }

  // Network first, so players always get the newest files when online (no stale
  // game after an update). If the network fails, fall back to the saved copy.
  // ignoreSearch matters: the page asks for "game.js?v=76" but the install step
  // saved plain "game.js", so without it the offline lookup would miss.
  event.respondWith(
    fetch(event.request)
      .then((response) => {
        if (response.ok) {
          const copy = response.clone();
          caches.open(CACHE).then((cache) => cache.put(event.request, copy));
        }
        return response;
      })
      .catch(() =>
        caches.match(event.request, { ignoreSearch: true }).then((cached) => cached || Response.error())
      )
  );
});
